def cp_gene_group(name, feature_type=None):
    """Resolve OGDRAW categories, using annotated RNA/region types first."""
    import re
    type_groups = {"tRNA": "transfer RNAs", "rRNA": "ribosomal RNAs",
                   "rep_origin": "origin of replication", "operon": "polycistronic transcripts",
                   "prim_transcript": "polycistronic transcripts", "intron": "introns"}
    feature_type = feature_type or (name if name in type_groups else None)
    if feature_type in type_groups:
        return type_groups[feature_type]
    for group, color, pattern in CPColorGroups:
        if re.search(pattern, name, re.IGNORECASE):
            return group


def cp_gene_color(name, feature_type=None):
    group = cp_gene_group(name, feature_type)
    return next(color for label, color, pattern in CPColorGroups if label == group)


